import {PNG} from 'pngjs';
/** Real engine resize, custom upload, channel continuity and entrance verification. */
import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
const base = process.env.KNOL_VERIFY_URL ?? 'http://127.0.0.1:3000';
const output = process.env.KNOL_VERIFY_OUTPUT ?? 'test-results/responsive-audio';
await mkdir(output, {recursive:true});
await writeFile('apps/web/public/runtime/verify-responsive-audio.html','<!doctype html><html><body style="margin:0"></body></html>');
const browser = await chromium.launch({headless:true});
try {
  const page = await browser.newPage({viewport:{width:1280,height:720}});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base+'/runtime/verify-responsive-audio.html');
  await page.evaluate(()=>{
    window.presenterEvents=[];
    addEventListener('message',event=>{if(event.origin===location.origin)window.presenterEvents.push(event.data);});
    document.body.innerHTML='<iframe src="/runtime/index.html" style="border:0;width:100vw;height:100vh"></iframe>';
  });
  await page.waitForFunction(()=>window.presenterEvents.some(e=>e.type==='ready'),null,{timeout:90000});
  let revision=0;
  const scene={contractVersion:1,sceneId:'audio-entry',width:1280,height:720,mode:'play',presentationEntry:'entry-1',actors:[],dialogue:{speaker:'나',text:'소리와 화면 구도가 실제 엔진에서 이어집니다.'},choices:[],presentation:{effects:[]},audio:{version:1,music:{action:'play',audioPath:'assets/audio/forest.wav',volume:.6,loop:true,fadeInMs:0,fadeOutMs:0},ambience:{action:'play',audioPath:'assets/audio/story-score/ambience-forest.ogg',volume:.25,loop:true,fadeInMs:0,fadeOutMs:0},sounds:[]}};
  const send=async(changes={},resources)=>{
    const value={...scene,...changes,revision:++revision};
    await page.evaluate(({value,resources})=>document.querySelector('iframe').contentWindow.postMessage({protocol:1,type:'loadScene',seq:value.revision,revision:value.revision,payload:value,...(resources?{audioResources:resources}:{})},location.origin),{value,resources});
    await page.waitForFunction(r=>window.presenterEvents.some(e=>e.type==='sceneRendered'&&e.revision===r),revision,{timeout:30000});
    return page.evaluate(r=>window.presenterEvents.find(e=>e.type==='sceneRendered'&&e.revision===r),revision);
  };
  const ambientOnly={...scene.audio,music:{action:'stop',fadeOutMs:0}};
  const waiting=await send({audio:ambientOnly});assert.equal(waiting.audioState.unlocked,false);assert.equal(waiting.audioState.musicStartCount,0,'sound waits for actual game gesture');
  await page.waitForTimeout(400);const stillWaiting=await send({audio:ambientOnly});assert.equal(stillWaiting.audioState.musicStartCount,0);
  assert.equal(stillWaiting.audioState.ambienceStartCount,0,'ambience-only waits for game gesture');
  await page.screenshot({path:output+'/audio-start-gate.png'});
  await page.mouse.click(640,360);
  await page.waitForFunction(()=>window.presenterEvents.some(e=>e.audioState?.unlocked&&e.audioState.ambienceStartCount===1),null,{timeout:10000});
  const first=await send();
  assert.equal(first.audioState.musicStartCount,1);
  assert.equal(first.audioState.ambienceStartCount,1);
  assert.equal(first.audioState.ambiencePath,scene.audio.ambience.audioPath,'bundled environmental loop plays with music');
  await page.waitForTimeout(700);
  const next=await send({sceneId:'next-cut',presentationEntry:'entry-2'});
  assert.equal(next.audioState.musicStartCount,1,'same music continues on next cut');
  assert.equal(next.audioState.ambienceStartCount,1,'ambient loop continues across cuts');
  const volumeRevision=await send({sceneId:'next-cut',presentationEntry:'entry-2',audio:{...scene.audio,ambience:{...scene.audio.ambience,volume:.15}}});
  assert.equal(volumeRevision.audioState.ambienceStartCount,1,'same-cut volume revision does not restart environment');
  assert.ok(next.audioState.musicPosition > first.audioState.musicPosition,'actual channel playback position advances');
  const sound={id:'cue',audioPath:'assets/audio/chime.wav',volume:.5,delayMs:0};
  await send({sceneId:'sound',presentationEntry:'entry-3',audio:{...scene.audio,sounds:[sound]}});
  const sounded=await send({sceneId:'sound',presentationEntry:'entry-3',audio:{...scene.audio,sounds:[sound]}});
  assert.equal(sounded.audioState.soundPlayCount,1,'same-scene revision does not replay SE');
  const edited=await send({mode:'edit'});
  assert.equal(edited.audioState.musicPath,null,'editor stops music');
  assert.equal(edited.audioState.ambiencePath,null,'editor stops environment');
  await page.setViewportSize({width:390,height:844});
  const portrait={width:720,height:1558,viewportVersion:1,textboxRect:{x:24,y:1012,width:672,height:480},dialogueStyle:{fontSize:38,speakerFontSize:34,padding:24}};
  const tall=await send({...portrait,presentationEntry:'entry-4'});
  assert.equal(tall.textboxRect.y,1012);
  assert.deepEqual(tall.engineLogicalSize,{width:720,height:1558});
  assert.ok(Math.abs(tall.engineViewport.height/tall.engineViewport.width-1558/720)<.01,'engine virtual ratio changes');
  await page.screenshot({path:output+'/portrait.png'});
  await page.setViewportSize({width:844,height:390});
  const wide=await send({width:1280,height:592,viewportVersion:1,textboxRect:{x:48,y:419,width:1184,height:134},dialogueStyle:{fontSize:30,speakerFontSize:28,padding:24},presentationEntry:'entry-4'});
  assert.ok(Math.abs(wide.engineViewport.height/wide.engineViewport.width-592/1280)<.01);
  assert.equal(wide.audioState.musicStartCount,tall.audioState.musicStartCount,'orientation change preserves track');
  assert.equal(wide.audioState.ambienceStartCount,tall.audioState.ambienceStartCount,'rotation preserves environment');
  await page.screenshot({path:output+'/landscape.png'});
  // File bytes enter the native filesystem; the engine decodes and plays them.
  const data=await readFile('apps/web/public/assets/audio/chime.wav');
  const hash=createHash('sha256').update(data).digest('hex');
  const resource={id:`audio:custom:${hash}:wav`,name:'업로드 효과음',mime:'audio/wav',kind:'sound',data:data.toString('base64')};
  const customAudio={version:1,music:{action:'stop',fadeOutMs:0},sounds:[{...sound,audioPath:`assets/audio/${hash}.wav`}]};
  await send({...portrait,sceneId:'custom',presentationEntry:'entry-5',audio:customAudio},[resource]);
  const custom=await send({...portrait,sceneId:'custom',presentationEntry:'entry-5',audio:customAudio});
  assert.equal(custom.audioState.soundPlayCount,2,'uploaded bytes play in native audio channel');
  assert.ok(custom.audioState.soundPaths.includes(`assets/audio/${hash}.wav`),'native decoder reports custom sound playing');
  assert.equal(custom.audioState.musicPath,null);
  const restarted=await send({...portrait,sceneId:'restart',presentationEntry:'entry-6',audio:{...scene.audio,sessionId:'new-run'}});
  assert.equal(restarted.audioState.musicStartCount,3,'explicit playback session starts music from beginning');
  assert.equal(restarted.audioState.ambienceStartCount,3,'restart session restarts environment');
  const sameRun=await send({...portrait,sceneId:'restart-next',presentationEntry:'entry-7',audio:{...scene.audio,sessionId:'new-run'}});
  assert.equal(sameRun.audioState.musicStartCount,3,'next cut in restarted session keeps track');
  assert.equal(sameRun.audioState.ambienceStartCount,3,'restarted next cut keeps environment');
  const ambienceStopped=await send({...portrait,sceneId:'ambient-stop',presentationEntry:'entry-8',audio:{...scene.audio,sessionId:'new-run',ambience:{action:'stop',fadeOutMs:0}}});
  assert.equal(ambienceStopped.audioState.ambiencePath,null,'environment can stop while music continues');
  assert.equal(ambienceStopped.audioState.musicStartCount,3,'environment stop leaves music identity');
  await page.setViewportSize({width:1280,height:720});
  const actor={id:'actor',name:'어른',imagePath:'assets/legacy-18da4fc/onggojib.character.classic-master.webp',rect:{x:100,y:60,width:240,height:450},motion:{version:1,type:'fade-out',offsetX:0,durationMs:1500,delayMs:0}};
  const actorChanges={sceneId:'actor-motion',width:1280,height:720,mode:'play',presentationEntry:'motion-1',actors:[actor],audio:{version:1,music:{action:'stop',fadeOutMs:0},sounds:[]}};
  const colors=async(left=110)=>{
    const png=PNG.sync.read(await page.locator('iframe').screenshot());const samples=new Set();
    for(let y=80;y<430;y+=3)for(let x=left;x<left+220;x+=3){const i=(y*png.width+x)*4;samples.add(png.data.slice(i,i+3).join(','));}return samples.size;
  };
  await send(actorChanges);const visible=await colors();assert.ok(visible>30,'actual actor appears at beginning of exit');
  await page.waitForTimeout(900);await send(actorChanges);await page.waitForTimeout(800);
  assert.ok(await colors()<5,'same-cut revision does not restart exit clock');
  await send({...actorChanges,presentationEntry:'motion-2',reducedMotion:true});assert.ok(await colors()<5,'reduced motion applies exit final state immediately');
  await send({...actorChanges,presentationEntry:'motion-3',reducedMotion:true,actors:[{...actor,motion:{...actor.motion,type:'fade-in'}}]});assert.ok(await colors()>30,'reduced motion applies entry final state immediately');
  await send({...actorChanges,presentationEntry:'motion-4',actors:[{...actor,motion:{...actor.motion,type:'move',offsetX:400,durationMs:1800}}]});
  assert.ok(await colors(510)>30,'actual movement begins at resolved offset');
  await page.waitForTimeout(2000);assert.ok(await colors()>30,'actual movement finishes at authored location');
  assert.ok(await colors(510)<5,'movement leaves initial location');
  await page.screenshot({path:output+'/actor-motion-final.png'});
  assert.equal(await page.locator('iframe').count(),1);
  assert.deepEqual(errors,[]);
  const bridgeErrors=await page.evaluate(()=>window.presenterEvents.filter(e=>e.type==='error'));
  assert.deepEqual(bridgeErrors,[]);
  console.log(JSON.stringify({verified:['dynamic-portrait','dynamic-landscape','one-instance','music-position-continuity','sound-once','editor-stop','custom-upload-native','ambience-only-unlock','independent-ambience','ambience-continuity-and-stop'],first,next,tall,wide,custom},null,2));
} finally {await browser.close();}
