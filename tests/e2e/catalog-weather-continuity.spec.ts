async function observedNative(page:Page){
 return page.getByTestId('story-runtime-frame').evaluate(frame=>{
  const scene=((frame as HTMLIFrameElement).contentWindow as WeatherWindow).__weatherScene,events=(window as WeatherWindow).__weatherEvents??[];
  const report=events.findLast(event=>event.type==='sceneRendered'&&event.sceneId===scene?.sceneId&&event.revision===scene?.revision);
  return {scene,report,transitionDone:events.some(event=>event.type==='presentationDone'&&event.sceneId===scene?.sceneId&&event.revision===scene?.revision)};
 });
}
async function nativeReady(page:Page):Promise<Awaited<ReturnType<typeof observedNative>>>{
 const status=page.getByTestId('story-runtime-status');
 await expect.poll(async()=>{
  const {scene,report}=await observedNative(page);
  return !!scene&&!!report&&scene.mode==='play'&&String(scene.revision)===await status.getAttribute('data-rendered-revision')&&String(scene.revision)===await status.getAttribute('data-scene-revision');
 },{timeout:120000,intervals:[25,50,100,250]}).toBe(true);
 const gate=page.getByTestId('story-runtime-frame').contentFrame().getByRole('button',{name:'소리 켜고 시작 · Enter 또는 Space',exact:true});
 if(await gate.count()){await gate.press('Enter');await expect(gate).toHaveCount(0);await expect(status).toHaveAttribute('data-audio-unlocked','true');return nativeReady(page);}
 const state=await observedNative(page);
 if(state.scene?.presentation?.transition&&!state.scene.transitionOnly)await expect.poll(async()=>(await observedNative(page)).transitionDone,{timeout:15000}).toBe(true);
 return observedNative(page);
}

