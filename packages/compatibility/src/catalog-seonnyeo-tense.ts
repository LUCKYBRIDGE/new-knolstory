const past=new Map(pairs);
/** Narration with every whole present-tense sentence put in the past; anything else stays as written. */
export function seonnyeoPastTense(text:string):string{
 return text.split(/((?<=[.!?…])[ \t]+|\n+)/u).map(part=>past.get(part)??part).join('');
}
